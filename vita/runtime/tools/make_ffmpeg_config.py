"""Writes FFmpeg's config.h for the PS Vita (VitaSDK, ARMv7, newlib).

Starts from the Linux aarch64 configuration that ReXGlue ships with its
FFmpeg checkout and changes what differs on the Vita:
- no architecture-specific code (plain C, no NEON/VFP assembly): every
  ARCH_* and the ARM feature flags become 0;
- no unaligned fast paths (ARMv7 LDRD/LDM fault on unaligned addresses);
- OS functions newlib on the Vita lacks.

Usage: py -3 -I make_ffmpeg_config.py <rexglue>/thirdparty/FFmpeg <out_dir>
Writes <out_dir>/config.h.
"""

import re
import sys
from pathlib import Path

OVERRIDES = {
    # ARM feature flags (generic C build)
    **{name: 0 for name in [
        "HAVE_ARMV5TE", "HAVE_ARMV6", "HAVE_ARMV6T2", "HAVE_ARMV8", "HAVE_NEON", "HAVE_VFP",
        "HAVE_VFPV3", "HAVE_ARMV5TE_EXTERNAL", "HAVE_ARMV6_EXTERNAL", "HAVE_ARMV6T2_EXTERNAL",
        "HAVE_ARMV8_EXTERNAL", "HAVE_NEON_EXTERNAL", "HAVE_VFP_EXTERNAL", "HAVE_VFPV3_EXTERNAL",
        "HAVE_ARMV5TE_INLINE", "HAVE_ARMV6_INLINE", "HAVE_ARMV6T2_INLINE", "HAVE_ARMV8_INLINE",
        "HAVE_NEON_INLINE", "HAVE_VFP_INLINE", "HAVE_VFPV3_INLINE", "HAVE_INLINE_ASM",
        "HAVE_INTRINSICS_NEON", "HAVE_VFP_ARGS",
    ]},
    "HAVE_FAST_UNALIGNED": 0,
    # newlib / VitaSDK
    "HAVE_ARC4RANDOM": 0,
    "HAVE_GETRUSAGE": 0,
    "HAVE_LSTAT": 0,
    "HAVE_MKSTEMP": 0,
    "HAVE_MMAP": 0,
    "HAVE_POSIX_MEMALIGN": 0,  # newlib has memalign() only; av_malloc uses it
    "HAVE_SCHED_GETAFFINITY": 0,
    "HAVE_SETRLIMIT": 0,
    "HAVE_SYSCONF": 0,
    "HAVE_ISATTY": 0,
    "HAVE_NANOSLEEP": 0,
    "HAVE_GETAUXVAL": 0,
    "HAVE_ELF_AUX_INFO": 0,
    "HAVE_PRCTL": 0,
    "HAVE_PTHREAD_SETNAME_NP": 0,
    "HAVE_PTHREAD_SET_NAME_NP": 0,
    "HAVE_SEM_TIMEDWAIT": 0,
    "HAVE_LIBDRM_GETFB2": 0,
}


def main() -> int:
    src = Path(sys.argv[1]) / "config_linux_aarch64.h"
    out_dir = Path(sys.argv[2])
    text = src.read_text(encoding="utf-8")
    seen = set()

    def repl(match: re.Match) -> str:
        name, value = match.group(1), match.group(2)
        if name.startswith("ARCH_"):
            seen.add(name)
            return f"#define {name} 0"
        if name in OVERRIDES:
            seen.add(name)
            return f"#define {name} {OVERRIDES[name]}"
        return match.group(0)

    text = re.sub(r"^#define (\w+) (\d+)$", repl, text, flags=re.M)
    missing = sorted(set(OVERRIDES) - seen)
    header = (
        "/* FFmpeg configuration for the PS Vita, generated by\n"
        " * vita/runtime/tools/make_ffmpeg_config.py from config_linux_aarch64.h. */\n")
    if missing:
        header += "/* not present in the source configuration: " + " ".join(missing) + " */\n"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "config.h").write_text(header + text, encoding="utf-8")
    print(f"config.h written; {len(seen)} values changed, {len(missing)} names absent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
