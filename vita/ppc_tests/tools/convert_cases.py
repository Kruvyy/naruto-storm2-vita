"""Convert ReXGlue's generated Catch2 test cases into a plain runner for the Vita.

The generated ppc_test_cases.cpp uses Catch2 and the desktop rex::memory::Memory
class. The checks themselves are kept verbatim; only the plumbing changes:
  * TEST_CASE("name", tags) { ... }  ->  static void vt_N(VitaTest& vt) { ... }
  * REQUIRE(x)                        ->  VITA_CHECK(x)   (records and returns)
  * memory[addr]                      ->  VITA_GUEST_BYTE(addr)   (soft MMU)
  * guest_base_arg(memory)            ->  vita_guest_base()
  * the get_memory()/virtual_membase() lines are dropped.

Usage: py -3 -I convert_cases.py <ppc_test_cases.cpp> <out_vita_test_cases.cpp>
"""
import re
import sys

TEST_RE = re.compile(r'^TEST_CASE\("([^"]+)",\s*"([^"]*)"\)\s*\{\s*$')
MEM_RE = re.compile(r"memory\[([^\]]+)\]")


def convert(src_lines):
    tests = []
    out = []
    i = 0
    n = len(src_lines)
    while i < n:
        m = TEST_RE.match(src_lines[i])
        if not m:
            i += 1
            continue
        name = m.group(1)
        idx = len(tests)
        tests.append(name)
        depth = 1
        body = []
        i += 1
        while i < n and depth > 0:
            line = src_lines[i]
            depth += line.count("{") - line.count("}")
            if depth <= 0:
                break
            s = line.strip()
            if s in ("auto& mem = get_memory();", "uint8_t* memory = mem.virtual_membase();"):
                i += 1
                continue
            line = line.replace("guest_base_arg(memory)", "vita_guest_base()")
            line = MEM_RE.sub(r"VITA_GUEST_BYTE(\1)", line)
            line = re.sub(r"\bREQUIRE\(", "VITA_CHECK(", line)
            if re.search(r"\bmemory\b", line):
                raise SystemExit(f"unconverted memory use in {name}: {line.strip()}")
            body.append(line)
            i += 1
        out.append(f"static void vt_{idx}(VitaTest& vt) {{\n")
        out.append("".join(l if l.endswith("\n") else l + "\n" for l in body))
        out.append("}\n\n")
        i += 1
    return tests, out


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        lines = f.readlines()
    tests, body = convert(lines)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by vita/ppc_tests/tools/convert_cases.py from ppc_test_cases.cpp\n")
        f.write("// DO NOT EDIT\n\n")
        f.write('#include <cstdint>\n#include <cstring>\n#include "ppc_config.h"\n')
        f.write('#include <rex/ppc.h>\n#include "ppc_test_decls.h"\n#include "vita_harness.h"\n\n')
        f.writelines(body)
        f.write("const VitaTestEntry kVitaTests[] = {\n")
        for idx, name in enumerate(tests):
            f.write(f'    {{"{name}", vt_{idx}}},\n')
        f.write("};\n")
        f.write(f"const unsigned kVitaTestCount = {len(tests)};\n")
    print(f"converted {len(tests)} test cases")


if __name__ == "__main__":
    main()
