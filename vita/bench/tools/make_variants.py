"""Generate the bench.* cases once per codegen register model (variant).

For each variant: `rexglue recompile-tests --set ...` on a bin dir holding only
bench.bin/bench.map, then every generated symbol `bench_XXXXXXXX` gets a
variant prefix (`v2_bench_XXXXXXXX`) so all variants link into one executable,
and the Catch2 cases are converted (same rules as vita/ppc_tests) into a table
`kBench_v2[]` with names "v2.bench.test_bench_int".

Usage: py -3 -I make_variants.py <rexglue.exe> <ppc bin dir> <asm dir> <out dir>
Writes <out>/<v>/{ppc_config.h, ppc_test_decls.h, ppc_test_functions.cpp,
cases.cpp} and <out>/variants.h.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "ppc_tests", "tools"))
import convert_cases  # noqa: E402

FLAGS = ["ctr_as_local=true", "xer_as_local=true", "cr_as_local=true", "reserved_as_local=true"]
VARIANTS = [
    ("v0", "base: every register in PPCContext (current Storm 2 build)", []),
    ("v1", "ctr/xer/cr/reserved as locals", FLAGS),
    ("v2", "v1 + r0/r2/r11/r12/f0/v32-63 as locals", FLAGS + ["non_argument_as_local=true"]),
    ("v3", "v2 + non-volatile r14-31/f14-31/v14-31/v64-127 as locals",
     FLAGS + ["non_argument_as_local=true", "non_volatile_as_local=true"]),
    ("v4", "v3 + skip_lr + skip_msr",
     FLAGS + ["non_argument_as_local=true", "non_volatile_as_local=true", "skip_lr=true", "skip_msr=true"]),
]


def main():
    rexglue, bin_dir, asm_dir, out = sys.argv[1:5]
    os.makedirs(out, exist_ok=True)
    only = os.path.join(out, "_bin")
    os.makedirs(only, exist_ok=True)
    for ext in ("bin", "map"):
        shutil.copy2(os.path.join(bin_dir, f"bench.{ext}"), os.path.join(only, f"bench.{ext}"))

    header = ["// Generated by vita/bench/tools/make_variants.py - DO NOT EDIT", "#pragma once",
              '#include "vita_harness.h"', ""]
    table = ["struct BenchVariant { const char* id; const char* desc; const VitaTestEntry* cases; unsigned count; };",
             "static const BenchVariant kBenchVariants[] = {"]
    for vid, desc, settings in VARIANTS:
        vdir = os.path.join(out, vid)
        if os.path.isdir(vdir):
            shutil.rmtree(vdir)
        cmd = [rexglue, "recompile-tests", "--bin-dir", only, "--asm-dir", asm_dir, "--output", vdir]
        for s in settings:
            cmd += ["--set", s]
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)

        sym = re.compile(r"\bbench_([0-9A-F]{8})\b")
        for name in ("ppc_test_functions.cpp", "ppc_test_decls.h", "ppc_test_cases.cpp"):
            p = os.path.join(vdir, name)
            text = open(p, encoding="utf-8").read()
            text = sym.sub(rf"{vid}_bench_\1", text)
            open(p, "w", encoding="utf-8", newline="\n").write(text)

        lines = open(os.path.join(vdir, "ppc_test_cases.cpp"), encoding="utf-8").readlines()
        tests, body = convert_cases.convert(lines)
        with open(os.path.join(vdir, "cases.cpp"), "w", encoding="utf-8", newline="\n") as f:
            f.write(f"// {vid}: {desc}\n// Generated by vita/bench/tools/make_variants.py - DO NOT EDIT\n\n")
            f.write('#include <cstdint>\n#include <cstring>\n#include "ppc_config.h"\n')
            f.write('#include <rex/ppc.h>\n#include "ppc_test_decls.h"\n#include "vita_harness.h"\n\n')
            f.write(f"namespace {vid} {{\n")
            f.writelines(body)
            f.write("}  // namespace\n\n")
            f.write(f"extern const VitaTestEntry kBench_{vid}[] = {{\n")
            for idx, name in enumerate(tests):
                f.write(f'    {{"{vid}.{name}", {vid}::vt_{idx}}},\n')
            f.write("};\n")
            f.write(f"extern const unsigned kBench_{vid}_count = {len(tests)};\n")
        header.append(f"extern const VitaTestEntry kBench_{vid}[];")
        header.append(f"extern const unsigned kBench_{vid}_count;")
        table.append(f'    {{"{vid}", "{desc}", kBench_{vid}, kBench_{vid}_count}},')
        print(f"{vid}: {len(tests)} cases ({' '.join(settings) or 'default'})")
    table.append("};")
    table.append(f"static const unsigned kBenchVariantCount = {len(VARIANTS)};")
    with open(os.path.join(out, "variants.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + [""] + table) + "\n")


if __name__ == "__main__":
    main()
